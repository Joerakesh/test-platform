// @ts-nocheck
"use client";

import Seal from "./Seal";
import { SCHOOL } from "@/lib/school";
import { optionLetters, QUESTION_TYPE_LABELS } from "@/lib/grading";
import { formatDateTime, formatSeconds } from "@/lib/format";

export default function PaperSheet({ test, meta = [], footer, questions, showAnswerKey = false, heading }: any) {
  const list = questions || test.questions || [];
  const totalMarks = test.totalMarks || list.reduce((s, q) => s + (Number(q.marks) || 0), 0);

  return (
    <div className="print-sheet">
      <div className="print-head">
        <Seal size="lg" />
        <div className="print-head-text">
          <div className="print-school">{SCHOOL.name}</div>
          <div className="print-school-tamil tamil">{SCHOOL.nameTamil}</div>
          <div className="tiny muted" style={{ letterSpacing: "0.16em", textTransform: "uppercase" }}>
            {SCHOOL.authority} · {SCHOOL.authorityTamil}
          </div>
        </div>
        <Seal size="lg" />
      </div>

      <div className="print-meta">
        <span>Academic Year: {test.academicYear || SCHOOL.academicYear}</span>
        <span>Date: {formatDateTime(new Date())}</span>
      </div>

      <div className="print-title">{heading || test.title}</div>

      <div className="print-meta">
        <span>
          <strong>Subject:</strong> {test.subject || "—"}
          {test.className ? ` · Class ${test.className}${test.sections?.length ? ` (${test.sections.join(", ")})` : ""}` : ""}
        </span>
        <span>
          <strong>Time:</strong> {test.duration} minutes
        </span>
        <span>
          <strong>Maximum Marks:</strong> {totalMarks}
        </span>
        <span>
          <strong>Questions:</strong> {list.length}
        </span>
      </div>

      {test.negativeMarking && (
        <div className="small" style={{ marginBottom: 14 }}>
          <strong>Note:</strong> Wrong answers carry negative marks as shown against each question.
        </div>
      )}

      {test.description && (
        <div className="small mb-2" style={{ whiteSpace: "pre-wrap" }}>
          {test.description}
        </div>
      )}

      {meta.length > 0 && (
        <table style={{ marginBottom: 18 }}>
          <tbody>
            {meta.map((row, i) => (
              <tr key={i}>
                <th style={{ width: 120, background: "var(--paper-2)", color: "var(--ink-700)", textTransform: "none", position: "static" }}>
                  {row[0]}
                </th>
                <td>{row[1]}</td>
                <th style={{ width: 120, background: "var(--paper-2)", color: "var(--ink-700)", textTransform: "none", position: "static" }}>
                  {row[2]}
                </th>
                <td>{row[3]}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}

      {list.map((q, i) => (
        <div className="print-q" key={i}>
          <div className="print-q-text">
            <strong>{i + 1}.</strong> {q.text}{" "}
            <span style={{ float: "right", color: "var(--ink-500)", fontSize: 12.5 }}>
              [{q.marks} mark{q.marks === 1 ? "" : "s"}
              {q.negativeMarks ? `, −${q.negativeMarks}` : ""}]
            </span>
          </div>

          {q.type === "short" ? (
            <div style={{ marginTop: 22, borderBottom: "1px dotted var(--ink-300)" }} />
          ) : (
            <div className="print-options">
              {(q.options || []).map((opt, oi) => {
                const correct =
                  showAnswerKey &&
                  (q.type === "multiselect"
                    ? (q.correctOptionIndexes || []).includes(oi)
                    : q.correctOptionIndex === oi);
                return (
                  <div key={oi}>
                    ({optionLetters(oi)}) {opt}
                    {correct && <strong style={{ color: "var(--green-700)" }}> ✓</strong>}
                  </div>
                );
              })}
            </div>
          )}

          {showAnswerKey && q.type === "short" && (
            <div className="tiny muted mt-1">Answer: {(q.correctAnswers || []).join(" / ")}</div>
          )}
        </div>
      ))}

      <div className="print-footer">
        <span>
          {SCHOOL.name} · {SCHOOL.place}
        </span>
        <span>{footer || "Generated by the Examination Cell"}</span>
      </div>
    </div>
  );
}

export function AttemptSummaryCard({ attempt, test }: any) {
  const total = attempt.totalMarks || test?.totalMarks || 0;
  const pct = total ? (attempt.score / total) * 100 : 0;
  return (
    <div className="grid grid-3">
      <div className="stat stat-red">
        <div className="stat-label">Score</div>
        <div className="stat-value">
          {attempt.score} <span style={{ fontSize: 16, color: "var(--ink-400)" }}>/ {total}</span>
        </div>
        <div className="stat-meta">{pct.toFixed(1)}% · {pct >= 40 ? "Pass" : "Fail"}</div>
      </div>
      <div className="stat stat-green">
        <div className="stat-label">Correct</div>
        <div className="stat-value">{attempt.correctCount}</div>
        <div className="stat-meta">{attempt.wrongCount} wrong · {attempt.skippedCount} skipped</div>
      </div>
      <div className="stat stat-gold">
        <div className="stat-label">Time taken</div>
        <div className="stat-value sm">{formatSeconds(attempt.timeSpentSeconds)}</div>
        <div className="stat-meta">{formatDateTime(attempt.submittedAt)}</div>
      </div>
    </div>
  );
}

export function TypeLabel({ type }: any) {
  return <span className="badge badge-grey">{QUESTION_TYPE_LABELS[type] || type}</span>;
}
